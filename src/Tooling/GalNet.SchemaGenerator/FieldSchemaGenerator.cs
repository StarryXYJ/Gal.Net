using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace GalNet.SchemaGenerator;

[Generator]
public sealed class FieldSchemaGenerator : IIncrementalGenerator
{
    private const string FieldName = "GalNet.Core.Parameters.FieldAttribute";
    private static readonly DiagnosticDescriptor Invalid = new("GNF001", "Unsupported field declaration", "{0}",
        "GalNet.Schema", DiagnosticSeverity.Error, true);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var declarations = context.SyntaxProvider.ForAttributeWithMetadataName("GalNet.Core.Parameters.GenerateFieldSchemaAttribute",
            static (node, _) => node is TypeDeclarationSyntax, static (ctx, _) => ctx);
        context.RegisterSourceOutput(declarations, static (output, declaration) => Generate(output, declaration));
    }

    private static void Generate(SourceProductionContext output, GeneratorAttributeSyntaxContext context)
    {
        var type = (INamedTypeSymbol)context.TargetSymbol;
        void Error(ISymbol symbol, string message) => output.ReportDiagnostic(Diagnostic.Create(Invalid, symbol.Locations.FirstOrDefault(), message));
        if (type.ContainingType != null || type.TypeParameters.Length != 0 || type.IsAbstract || context.TargetNode is not ClassDeclarationSyntax declaration ||
            !declaration.Modifiers.Any(SyntaxKind.PartialKeyword))
        { Error(type, "Use a top-level, non-generic, concrete partial class."); return; }
        var members = type.GetMembers().Select(member => (Member: member,
            Attribute: member.GetAttributes().FirstOrDefault(attribute => attribute.AttributeClass?.ToDisplayString() == FieldName)))
            .Where(item => item.Attribute != null).OrderBy(item => (int)item.Attribute!.ConstructorArguments[0].Value!).ToArray();
        var fields = new List<(IPropertySymbol Member, string Id, AttributeData Attribute, string? Default)>();
        var orders = new HashSet<int>();
        var ids = new HashSet<string>(StringComparer.Ordinal);
        foreach (var item in members)
        {
            if (!(item.Member is IPropertySymbol property) || property.IsStatic || property.IsIndexer ||
                property.GetMethod?.DeclaredAccessibility != Accessibility.Public ||
                property.SetMethod?.DeclaredAccessibility != Accessibility.Public || property.SetMethod.IsInitOnly)
            { Error(item.Member, "Field requires a public readable/writable property. Annotate the property, including an ObservableProperty partial property, rather than its backing field."); return; }
            var jsonName = property.GetAttributes().FirstOrDefault(attribute => attribute.AttributeClass?.ToDisplayString() == "System.Text.Json.Serialization.JsonPropertyNameAttribute");
            var id = jsonName == null ? CamelName(property.Name) : jsonName.ConstructorArguments[0].Value as string ?? "";
            if (string.IsNullOrWhiteSpace(id) || !ids.Add(id) || !orders.Add((int)item.Attribute!.ConstructorArguments[0].Value!))
            { Error(property, "Field JSON names and orders must be non-empty/unique."); return; }
            if (property.GetAttributes().Any(attribute => attribute.AttributeClass?.ToDisplayString() == "System.Text.Json.Serialization.JsonIgnoreAttribute"))
            { Error(property, "An editable field cannot also be JsonIgnore."); return; }
            string? defaultValue = null;
            var syntax = property.DeclaringSyntaxReferences.Select(reference => reference.GetSyntax()).OfType<PropertyDeclarationSyntax>().First();
            if (syntax.Initializer != null)
            {
                var constant = context.SemanticModel.Compilation.GetSemanticModel(syntax.SyntaxTree).GetConstantValue(syntax.Initializer.Value);
                if (!constant.HasValue) { Error(property, "Field defaults must be constant initializers; constructors and arbitrary expressions are not evaluated."); return; }
                defaultValue = constant.Value == null ? "null" : SymbolDisplay.FormatPrimitive(constant.Value, true, false);
            }
            fields.Add((property, id, item.Attribute!, defaultValue));
        }
        var code = new StringBuilder("// <auto-generated/>\n#nullable enable\n");
        if (!type.ContainingNamespace.IsGlobalNamespace) code.Append("namespace ").Append(type.ContainingNamespace.ToDisplayString()).AppendLine(";");
        code.Append("partial class @").Append(type.Name).Append(" : global::GalNet.Core.Parameters.IFieldDto, global::GalNet.Core.Parameters.IFieldSchema<")
            .Append(type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)).AppendLine(">\n{");
        code.AppendLine("public static global::System.Collections.Generic.IReadOnlyList<global::GalNet.Core.Parameters.FieldDescriptor> Schema { get; } = CreateFieldSchema();");
        code.AppendLine("global::System.Collections.Generic.IReadOnlyList<global::GalNet.Core.Parameters.FieldDescriptor> global::GalNet.Core.Parameters.IFieldDto.Fields => Schema;");
        code.AppendLine("private static global::System.Collections.Generic.IReadOnlyList<global::GalNet.Core.Parameters.FieldDescriptor> CreateFieldSchema()\n{");
        for (var i = 0; i < fields.Count; i++)
        {
            var field = fields[i];
            var valueType = field.Member.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            var constraints = field.Attribute.NamedArguments.Where(argument => argument.Key is "Minimum" or "Maximum" or "MaxLength" or "ValueFormat")
                .Select(argument => "[" + Quote(argument.Key == "ValueFormat" ? "format" : char.ToLowerInvariant(argument.Key[0]) + argument.Key.Substring(1)) + "] = " + argument.Value.ToCSharpString());
            var converter = field.Member.GetAttributes().FirstOrDefault(attribute => attribute.AttributeClass?.ToDisplayString() == "System.Text.Json.Serialization.JsonConverterAttribute");
            var options = converter == null ? "null" : "new global::System.Text.Json.JsonSerializerOptions { Converters = { new " +
                ((ITypeSymbol)converter.ConstructorArguments[0].Value!).ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) + "() } }";
            code.Append("var v").Append(i).Append(" = new global::GalNet.Core.Parameters.ValueDescriptor(typeof(").Append(valueType)
                .Append("), allowNull: ").Append(Named(field.Attribute, "AllowNull", "null")).Append(", constraints: global::System.Text.Json.JsonSerializer.SerializeToElement(new global::System.Collections.Generic.Dictionary<string, object?> { ")
                .Append(string.Join(", ", constraints)).Append(" }), jsonOptions: ").Append(options).AppendLine(");");
        }
        code.AppendLine("return global::System.Array.AsReadOnly(new global::GalNet.Core.Parameters.FieldDescriptor[] {");
        for (var i = 0; i < fields.Count; i++)
        {
            var field = fields[i];
            code.Append("new(").Append(Quote(field.Id)).Append(", v").Append(i).Append(", isRequired: ")
                .Append(field.Member.IsRequired || field.Member.GetAttributes().Any(attribute => attribute.AttributeClass?.ToDisplayString() == "System.Text.Json.Serialization.JsonRequiredAttribute")
                    ? "true" : Named(field.Attribute, "Required", "false"))
                .Append(", defaultValue: ").Append(field.Default == null ? "null" : "global::GalNet.Core.Parameters.ValueCodec.Serialize(v" + i + ", (" + CastType(field.Member.Type) + ")" + field.Default + ")")
                .Append(", editor: new global::GalNet.Core.Parameters.EditorHints(").Append(Named(field.Attribute, "EditorId", "null"))
                .Append(", ").Append(Named(field.Attribute, "Step", "null")).Append(", ").Append(Named(field.Attribute, "Format", "null"))
                .Append(", ").Append(Named(field.Attribute, "UnitKey", "null"))
                .Append("), labelKey: ").Append(Named(field.Attribute, "LabelKey", "null")).Append(", descriptionKey: ")
                .Append(Named(field.Attribute, "DescriptionKey", "null")).AppendLine("),");
        }
        code.AppendLine("});\n}");
        code.AppendLine("object? global::GalNet.Core.Parameters.IFieldDto.ReadField(string id) => id switch {");
        foreach (var field in fields) code.Append(Quote(field.Id)).Append(" => this.@").Append(field.Member.Name).AppendLine(",");
        code.AppendLine("_ => throw new global::System.ArgumentException(\"Unknown DTO field.\", nameof(id)) };\n");
        code.AppendLine("void global::GalNet.Core.Parameters.IFieldDto.WriteField(string id, object? value) { switch (id) {");
        foreach (var field in fields) code.Append("case ").Append(Quote(field.Id)).Append(": this.@").Append(field.Member.Name).Append(" = (")
            .Append(CastType(field.Member.Type)).AppendLine(")value!; break;");
        code.AppendLine("default: throw new global::System.ArgumentException(\"Unknown DTO field.\", nameof(id)); } }\n}");
        output.AddSource(type.ToDisplayString().Replace("@", "") + ".Fields.g.cs", code.ToString());
    }

    private static string Quote(string value) => SymbolDisplay.FormatLiteral(value, true);
    private static string CamelName(string name)
    {
        var characters = name.ToCharArray();
        for (var index = 0; index < characters.Length; index++)
        {
            if (!char.IsUpper(characters[index])) break;
            if (index > 0 && index + 1 < characters.Length && !char.IsUpper(characters[index + 1])) break;
            characters[index] = char.ToLowerInvariant(characters[index]);
        }
        return new string(characters);
    }
    private static string CastType(ITypeSymbol type) => type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat.WithMiscellaneousOptions(
        SymbolDisplayFormat.FullyQualifiedFormat.MiscellaneousOptions | SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier));
    private static string Named(AttributeData attribute, string name, string fallback) =>
        attribute.NamedArguments.FirstOrDefault(argument => argument.Key == name) is var argument && argument.Key != null
            ? argument.Value.ToCSharpString() : fallback;
}
